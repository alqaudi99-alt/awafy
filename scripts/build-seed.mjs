// Generates supabase/seed.sql from the prototype data. DEV/STAGING ONLY — fictional pharmacies.
import fs from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const d = JSON.parse(fs.readFileSync(root + 'supabase/seed-data/prototype-data.json', 'utf8'));
const q = v => v === null || v === undefined || v === '' ? 'null' : typeof v === 'number' ? String(v) : typeof v === 'boolean' ? String(v) : `'${String(v).replace(/'/g, "''")}'`;
const out = ['-- GENERATED by scripts/build-seed.mjs. Development/staging only. Pharmacies are fictional demo data.', 'begin;'];

const cats = [...new Map(d.products.map(p => [p.cat, p.catEn])).entries()];
cats.forEach(([ar, en], i) => out.push(`insert into public.categories (name_ar, name_en, sort_order) values (${q(ar)}, ${q(en)}, ${i});`));

for (const p of d.products) {
  out.push(`insert into public.products (category_id, name_ar, name_en, usage_ar, usage_en, requires_rx) values ((select id from public.categories where name_ar = ${q(p.cat)}), ${q(p.name)}, ${q(p.nameEn)}, ${q(p.dose)}, ${q(p.doseEn)}, ${p.rx});`);
}

const offsets = [0, 0.15, -0.10];
d.pharmacies.forEach((ph, i) => {
  out.push(`insert into public.pharmacies (name_ar, name_en, license_number, address, delivery_fee_omr, is_verified) values (${q(ph.name + ' (تجريبي)')}, ${q(ph.nameEn + ' (Demo)')}, ${q('DEMO-' + (i + 1))}, 'Muscat (demo)', 0.500, true);`);
  for (const p of d.products) {
    const price = Math.max(0.5, Math.round((p.price + offsets[i]) * 1000) / 1000);
    out.push(`insert into public.pharmacy_stock (pharmacy_id, product_id, price_omr, quantity) values ((select id from public.pharmacies where license_number = 'DEMO-${i + 1}'), (select id from public.products where name_ar = ${q(p.name)}), ${price.toFixed(3)}, 50);`);
  }
});

const known = {
  'Honey - For Cough': 'DATA ISSUE: fixed 2.5-5 ml dose is stored as per-kg; calculator shows mg per kg. Must be corrected before approval.',
  "Ibuprofen - Children's Syrup": 'DATA ISSUE: max daily 30 is mg/kg/day but displayed as mg/day. Standardise units before approval.',
  'Ondansetron - Children': 'DATA ISSUE: 0.15 mg/kg dose stored as fixed (not weight-based). Confirm before approval.',
};
for (const r of d.dosage) {
  out.push(`insert into public.dosage_reference (drug_name_ar, drug_name_en, age_group_ar, age_group_en, min_weight_kg, dose_text, weight_based, per_kg_low, per_kg_high, max_single_mg, max_daily, frequency_ar, frequency_en, warnings_ar, warnings_en, requires_rx, review_note) values (${[r.name, r.nameEn, r.age, r.ageEn, r.minWeight, r.doseText, r.weightBased, r.perKgLow, r.perKgHigh, r.maxSingle, r.maxDaily ? String(r.maxDaily) : null, r.freq, r.freqEn, r.warnings, r.warningsEn, r.rx, known[r.nameEn] ?? 'Imported from prototype; awaiting pharmacist review.'].map(q).join(', ')});`);
}
for (const s of d.symptoms) {
  out.push(`insert into public.symptom_reference (body_region, name_ar, name_en, age_group_ar, age_group_en, suggestion_ar, suggestion_en, red_flags_ar, red_flags_en, review_note) values (${[s.region, s.name, s.nameEn, s.age, s.ageEn, s.suggestion, s.suggestionEn, s.redFlags, s.redFlagsEn, 'Imported from prototype; awaiting pharmacist review.'].map(q).join(', ')});`);
}
out.push('commit;');
fs.writeFileSync(root + 'supabase/seed.sql', out.join('\n') + '\n');
console.log('seed lines', out.length);
